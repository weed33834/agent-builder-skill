// ===================== 工具函数 =====================

/** 取年中的第几天(1-366) */
function dayOfYear(d: Date): number {
  const start = new Date(d.getFullYear(), 0, 0)
  const diff = d.getTime() - start.getTime()
  return Math.floor(diff / 86400000)
}

/** 按日期取当日名言(同一天稳定,跨天轮换) */
export function getDailyQuote(date = new Date()): DailyQuote {
  const idx = dayOfYear(date) % DAILY_QUOTES.length
  return DAILY_QUOTES[idx]
}

/** 按 MM-DD 取当日历史事件 */
export function getHistoryToday(date = new Date()): HistoryEvent[] {
  const mm = String(date.getMonth() + 1).padStart(2, '0')
  const dd = String(date.getDate()).padStart(2, '0')
  const key = `${mm}-${dd}`
  // 若当日无数据,用日期哈希从全年取一条兜底
  if (!HISTORY_TODAY[key]) {
    const fallbackIdx = dayOfYear(date) % 36
    const all: HistoryEvent[] = []
    for (const k in HISTORY_TODAY) all.push(...HISTORY_TODAY[k])
    return [all[fallbackIdx % all.length]]
  }
  return HISTORY_TODAY[key]
}
